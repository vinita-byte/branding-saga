export type PageKind = "home" | "about" | "archetype";

/** Title, description and path for a page. Shared by the client SEO tags and the build-time HTML. */
export function pageMeta(archetype: Archetype | undefined, page: PageKind) {
  const isAbout = page === "about";
  const title = archetype
    ? `${archetype.name} Brand Archetype — Visual & Verbal Playbook | Branding Saga`
    : isAbout
      ? "About Brand Archetypes | Branding Saga"
      : "Branding Saga — The 12 Brand Archetypes";
  const description = archetype
    ? `Explore the ${archetype.name} brand archetype: ${archetype.desire.toLowerCase()}, visual identity, color palette, typography, voice, word bank, taglines, hooks, and content ideas.`
    : isAbout
      ? "Learn what brand archetypes are and how to use Branding Saga to create a coherent visual identity, verbal identity, and memorable brand character."
      : "The visual and verbal playbook for all 12 brand archetypes, with practical guidance for color, typography, imagery, voice, taglines, hooks, and content.";
  const path = archetype ? `/${archetype.slug}` : isAbout ? "/about" : "/";
  return { title, description, path, canonical: `${SITE_URL}${path}` };
}
